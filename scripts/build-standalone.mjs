// Build a single self-contained HTML file.
//
// The result has no imports, no module loading and no server requirement:
// three.js, every source file, the stylesheet and all four example
// programs are inlined, and the script is a plain IIFE so it runs straight
// off the filesystem. Double-click dist/mill-sim.html and it works.
//
// esbuild is not a dependency of this project. Install it first:
//
//   npm i -D esbuild
//   npm run build

import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join, resolve } from 'node:path';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));

let esbuild;
try {
  esbuild = await import('esbuild');
} catch {
  console.error('esbuild is not installed. Run:  npm i -D esbuild && npm run build');
  process.exit(2);
}

/**
 * The examples module fetches its G-code at runtime. A single file has
 * nothing to fetch from, so it is replaced with one that carries the
 * programs inline.
 */
async function inlineExamples() {
  const src = await readFile(join(ROOT, 'src/examples.js'), 'utf8');
  const match = /export const EXAMPLES = (\[[\s\S]*?\]);/.exec(src);
  if (!match) throw new Error('Could not find EXAMPLES in src/examples.js');
  const examples = JSON.parse(match[1]);

  for (const ex of examples) {
    ex.code = await readFile(join(ROOT, ex.file), 'utf8');
  }

  return `// Generated by scripts/build-standalone.mjs — programs inlined.
export const EXAMPLES = ${JSON.stringify(examples, null, 2)};
export async function loadExample(example) {
  const found = EXAMPLES.find((e) => e.file === example.file);
  if (!found) throw new Error('Unknown example: ' + example.file);
  return found.code;
}
`;
}

const inlineExamplesPlugin = (source) => ({
  name: 'inline-examples',
  setup(build) {
    build.onLoad({ filter: /src[\\/]examples\.js$/ }, () => ({ contents: source, loader: 'js' }));
  },
});

const html = (css, js) => `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Mill-Sim — CNC mill simulator</title>
<meta name="description" content="Browser CNC milling simulator: parametric tool library, G-code interpretation, collision checking and material removal.">
<link rel="icon" href="data:image/svg+xml,<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 32 32'><rect width='32' height='32' rx='6' fill='%23171b24'/><path d='M8 7h4v11a4 4 0 0 0 8 0V7h4v11a8 8 0 0 1-16 0z' fill='%234fd1c5'/></svg>">
<style>
${css}
</style>
</head>
<body>
<div id="app" class="app"></div>
<noscript>Mill-Sim needs JavaScript and a WebGL2-capable browser.</noscript>
<div id="boot" class="boot">
  <div class="boot-inner">
    <div class="boot-mark">⌗</div>
    <div class="boot-title">Mill-Sim</div>
    <div class="boot-sub">starting up…</div>
  </div>
</div>
<script>
${js}
</script>
<script>
(function () {
  var boot = document.getElementById('boot');
  function fail(message, detail) {
    boot.innerHTML = '';
    var box = document.createElement('div');
    box.className = 'boot-inner boot-error';
    box.innerHTML = '<div class="boot-title">Could not start</div><p>' + message + '</p>';
    if (detail) {
      var pre = document.createElement('pre');
      pre.textContent = detail;
      box.appendChild(pre);
    }
    boot.appendChild(box);
  }
  try {
    if (!document.createElement('canvas').getContext('webgl2')) {
      fail('This browser does not expose WebGL2, which the material-removal renderer needs.');
      return;
    }
    window.millsim = new window.MillSim.App(document.getElementById('app'));
    boot.remove();
  } catch (err) {
    console.error(err);
    fail('Mill-Sim hit an error while starting.', err && err.stack ? err.stack : String(err));
  }
}());
</script>
</body>
</html>
`;

const examplesSource = await inlineExamples();

const result = await esbuild.build({
  entryPoints: [join(ROOT, 'src/app.js')],
  bundle: true,
  write: false,
  format: 'iife',
  globalName: 'MillSim',
  target: ['es2020'],
  minify: true,
  legalComments: 'none',
  logLevel: 'warning',
  plugins: [inlineExamplesPlugin(examplesSource)],
  alias: {
    three: join(ROOT, 'vendor/three/three.module.min.js'),
    'three/addons/controls/OrbitControls.js': join(ROOT, 'vendor/three/addons/controls/OrbitControls.js'),
    'three/addons/controls/TransformControls.js': join(ROOT, 'vendor/three/addons/controls/TransformControls.js'),
  },
});

const js = result.outputFiles[0].text;
const css = await readFile(join(ROOT, 'styles/app.css'), 'utf8');
const page = html(css, js);

await mkdir(join(ROOT, 'dist'), { recursive: true });
const out = join(ROOT, 'dist/mill-sim.html');
await writeFile(out, page);

console.log(`Wrote ${out}`);
console.log(`  ${(page.length / 1024 / 1024).toFixed(2)} MB — open it directly in a browser, no server needed.`);
